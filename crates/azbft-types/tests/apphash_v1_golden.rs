#[test]
fn app_hash_statement_v1_borsh_encoding_is_frozen() {
    let statement = statement();
    let expected = [
        0x39, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2a, 0x2b, 0x2c, 0x2d,
        0x2e, 0x2f, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3a, 0x3b, 0x3c,
        0x3d, 0x3e, 0x3f, 0x10, 0x27, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x27, 0x21, 0x8c, 0x33,
        0x8f, 0xc1, 0x78, 0x3c, 0x1e, 0xd3, 0x77, 0xcd, 0x10, 0x04, 0x0d, 0x5f, 0x81, 0x27, 0xa2,
        0x75, 0x8a, 0x5a, 0x01, 0xcc, 0xfc, 0x91, 0xa6, 0xd7, 0x6c, 0x9b, 0x66, 0xcb,
    ];
    let bytes = borsh::to_vec(&statement).expect("statement serializes");
    assert_eq!(bytes, expected);
    assert_eq!(
        borsh::from_slice::<AppHashStatementV1>(&bytes).unwrap(),
        statement
    );
    assert_eq!(statement.id(), azbft_types::blake3_id(&statement));
}

#[test]
fn app_hash_vote_and_certificate_v1_roundtrip_borsh() {
    let statement = statement();
    let vote = AppHashVoteV1 {
        statement: statement.clone(),
        voter: NodeId([7; 20]),
        signature: vec![1, 2, 3],
    };
    assert_eq!(
        borsh::from_slice::<AppHashVoteV1>(&borsh::to_vec(&vote).unwrap()).unwrap(),
        vote
    );

    for agg in [
        AggSig::Secp(vec![(NodeId([1; 20]), vec![9; 64])]),
        AggSig::Bls(BlsAgg {
            agg_sig: [0xab; 96],
            signers: vec![NodeId([1; 20]), NodeId([2; 20])],
        }),
    ] {
        let cert = AppHashCertV1 {
            statement: statement.clone(),
            agg,
        };
        assert_eq!(
            borsh::from_slice::<AppHashCertV1>(&borsh::to_vec(&cert).unwrap()).unwrap(),
            cert
        );
    }
}

#[test]
fn validator_set_hash_v1_is_the_borsh_blake3_id() {
    let vset = azbft_types::ValidatorSet::new_members(vec![azbft_types::Member::secp_only(
        NodeId([9; 20]),
        vec![1, 2, 3],
        1,
    )]);
    assert_eq!(
        azbft_types::validator_set_hash(&vset),
        azbft_types::blake3_id(&vset)
    );
}
